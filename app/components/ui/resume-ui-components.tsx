// Button
export interface ButtonProps extends React.ButtonHTMLAttributes<HTMLButtonElement> {
    variant?: "default" | "destructive" | "outline" | "secondary" | "ghost" | "link"
    size?: "default" | "sm" | "lg" | "icon"
  }
  
  export const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
    ({ className, variant = "default", size = "default", ...props }, ref) => {
      return (
        <button
          className={cn(
            "inline-flex items-center justify-center rounded-xl text-sm font-bold tracking-wide ring-offset-background transition-all focus-visible:outline-none focus-visible:ring-4 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 shadow-lg hover:shadow-2xl active:scale-95 duration-200",
            {
              "bg-gradient-to-r from-indigo-500 to-purple-600 text-white hover:from-indigo-600 hover:to-purple-700": variant === "default",
              "bg-red-600 text-white hover:bg-red-700": variant === "destructive",
              "border-2 border-indigo-500 text-indigo-500 hover:bg-indigo-500 hover:text-white": variant === "outline",
              "bg-gray-800 text-white hover:bg-gray-900": variant === "secondary",
              "text-indigo-500 hover:text-indigo-700": variant === "ghost",
              "text-indigo-500 underline-offset-4 hover:underline": variant === "link",
              "h-12 px-6 py-3": size === "default",
              "h-10 rounded-lg px-5": size === "sm",
              "h-14 rounded-lg px-10 text-lg": size === "lg",
              "h-12 w-12": size === "icon",
            },
            className,
          )}
          ref={ref}
          {...props}
        />
      )
    },
  )
  Button.displayName = "Button"

